/*
UNIT tests for booking-dao.
The database is mocked: we check how a party is seated on the tables and what gets saved.
The SQL itself and the rollback of the transaction are covered by the integration tests.
*/

vi.mock("../../database/database", () => ({
    db: { prepare: vi.fn(), transaction: vi.fn() },
}));

vi.mock("../../dao/dietary-requirement-dao", () => ({
    getDietaryRequirementsByBooking: vi.fn(),
    replaceRequirements: vi.fn(),
}));
const DATE = "2026-11-02";
const START = "19:00";
const HIKER_ID = 5;
const BOOKING_ID = 42;
const NOW = "2026-11-02 12:00";

// get is needed by getBooking, which reads a single row
const statement = { all: vi.fn(), run: vi.fn(), get: vi.fn() };

const table = (table_number: number, seats: number, free_seats = seats) => ({ table_number, seats, free_seats });

const requirement = (allergy_flag: boolean, description: string): RequirementInput => ({ allergy_flag, description });

// the example of the story: three requirements for three subsets of the party
const STORY_REQUIREMENTS = [
    requirement(true, "1 vegan, peanut allergy"),
    requirement(true, "1 shellfish allergy"),
    requirement(false, "2 vegetarians"),
];

// what replaceRequirements would return for the given requirements
const saved = (inputs: RequirementInput[]) =>
    inputs.map((r, i) => new DietaryRequirement(i + 1, BOOKING_ID, r.allergy_flag, r.description));

const book = (party_size: number, requirements?: RequirementInput[]) =>
    saveBooking(HIKER_ID, DATE, START, party_size, requirements);

// [table_number, assigned_seats] of each seating, to keep the expectations short
const seatsOf = (party_size: number) =>
    book(party_size)!.seatings.map((s) => [s.table_number, s.assigned_seats]);

const check = (party_size: number) => getBookingAvailability(DATE, START, party_size);

// [table_number, assigned_seats] of each proposed table, like seatsOf
const split = (party_size: number) =>
    check(party_size)!.map((a) => [a.table_number, a.assigned_seats]);

const seating = (table_number: number, assigned_seats: number, booking_id = BOOKING_ID, date = DATE, start = START) =>
    new SeatedAt(booking_id, date, start, table_number, assigned_seats);

beforeEach(() => {
    vi.mocked(replaceRequirements).mockReturnValue([]);
    vi.resetAllMocks();
    vi.mocked(getDietaryRequirementsByBooking).mockReturnValue([]);
    vi.mocked(db.prepare).mockReturnValue(statement as any);
    vi.mocked(db.transaction).mockImplementation(((callback: () => unknown) => callback) as any);
    statement.run.mockReturnValue({ changes: 1, lastInsertRowid: BOOKING_ID });
});

describe("getTablesAvailability (unit)", () => {
    it("returns the tables of the slot as given by the query", () => {
        const tables = [table(1, 4, 2), table(2, 6)];
        statement.all.mockReturnValue(tables);

        expect(getTablesAvailability(DATE, START)).toEqual(tables);
    });

    it("queries the requested slot", () => {
        statement.all.mockReturnValue([]);

        getTablesAvailability(DATE, START);
        
        expect(statement.all).toHaveBeenCalledWith(DATE, START);
    });
});

describe("saveBooking (unit)", () => {
    it("returns the booking of the hiker with the id generated by the database", () => {
        statement.all.mockReturnValue([table(1, 4)]);

        const { booking } = book(2)!;

        expect(booking).toBeInstanceOf(Booking);
        expect(booking).toEqual(new Booking(BOOKING_ID, HIKER_ID));
    });

    it("saves the booking and one seating per assigned table", () => {
        statement.all.mockReturnValue([table(1, 4), table(2, 6)]);

        const result = book(9)!;
        const seatings = result.seatings;

        expect(statement.run).toHaveBeenCalledTimes(3);
        expect(statement.run).toHaveBeenNthCalledWith(1, HIKER_ID);
        expect(statement.run).toHaveBeenNthCalledWith(2, BOOKING_ID, DATE, START, 2, 6);
        expect(statement.run).toHaveBeenNthCalledWith(3, BOOKING_ID, DATE, START, 1, 3);
        expect(seatings).toEqual([
            new SeatedAt(BOOKING_ID, DATE, START, 2, 6),
            new SeatedAt(BOOKING_ID, DATE, START, 1, 3),
        ]);
    });

    it("returns null and saves nothing when the slot has not enough free seats", () => {
        statement.all.mockReturnValue([table(1, 4), table(2, 6, 3)]);

        expect(book(8)).toBeNull();
        expect(statement.run).not.toHaveBeenCalled();
    });

    it("does every read and write inside the transaction", () => {
        // the transaction never runs its callback: nothing must touch the database
        vi.mocked(db.transaction).mockReturnValue((() => null) as any);

        book(2);

        expect(db.transaction).toHaveBeenCalledTimes(1);
        expect(statement.all).not.toHaveBeenCalled();
        expect(statement.run).not.toHaveBeenCalled();
    });

    it("lets a database failure through instead of swallowing it", () => {
        const boom = new Error("FOREIGN KEY constraint failed");
        statement.all.mockReturnValue([table(1, 4)]);
        statement.run.mockImplementation(() => {
            throw boom;
        });

        expect(() => book(2)).toThrow(boom);
    });
});

describe("getBookingAvailability (unit)", () => {
    it("queries the requested slot", () => {
        // the free seats must be read for this date and start time, not for another slot
        // Arrange
        statement.all.mockReturnValue([]);

        // Act
        check(2);

        // Assert
        expect(statement.all).toHaveBeenCalledWith(DATE, START);
    });

    it("only reads: it never saves or reserves seats", () => {
        // checking availability is public and must not change the database
        // Arrange
        statement.all.mockReturnValue([table(1, 4), table(2, 6)]);

        // Act
        check(9);

        // Assert
        expect(statement.run).not.toHaveBeenCalled();
        expect(db.transaction).not.toHaveBeenCalled();
    });

    it("proposes the same tables that a booking would then get", () => {
        // the user must be shown the arrangement they will really get when booking
        // Arrange
        statement.all.mockReturnValue([table(1, 4), table(2, 6)]);

        // Act
        const proposed = split(9);
        const booked = seatsOf(9);

        // Assert
        expect(proposed).toEqual([[2, 6], [1, 3]]);
        expect(booked).toEqual(proposed);
    });

    it("lets a database failure through instead of swallowing it", () => {
        // a broken database must give an error, not look like "no seats available"
        // Arrange
        const boom = new Error("SQLITE_BUSY: database is locked");
        statement.all.mockImplementation(() => {
            throw boom;
        });

        // Act
        const act = () => check(2);

        // Assert
        expect(act).toThrow(boom);
    });
});

